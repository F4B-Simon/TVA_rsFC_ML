def nested_cv(X, y, X_fu=None, y_fu=None, repeats=10, seed=0,
              n_runs=1000, n_random=10_000):
    """Nested CV: every label-dependent step runs on the outer training set only;
    the held-out fold is predicted once. X_fu, y_fu: follow-up data of the same
    participants (y_fu = -1 if middle or missing at follow-up). Each fold model
    is applied, frozen, to the follow-up data of its held-out participants
    (nested transfer). Returns the pooled AUC of each repetition (Table 2:
    mean ± SD) for baseline and follow-up."""
