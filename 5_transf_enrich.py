"""### Transfer Enrichment Function

This function calculates the transfer enrichment of feature sets trained on baseline data and evaluated on follow-up data, along with its null distribution and family-wise error rate (FWER) corrected p-values.
"""

def transfer_enrichment(Xtr, y_train, Xte, y_fu, n_sets=1_000_000, top=1000,
                        size=6, n_perm=200, seed=0):
    """Xtr, Xte: baseline low/high and follow-up low/high data, standardized with
    all 69 baseline participants as in S4. Random six-feature sets are trained at
    baseline and applied, frozen, to follow-up. Enrichment = occurrences of each
    feature among the `top` sets with the highest transfer AUC / chance
    expectation (top * size / 136). Descriptive,
    because the best sets are selected on the follow-up data. Null distribution:
    follow-up labels permuted (training unchanged); family-wise p against the
    maximum enrichment across all features."""
    rng = np.random.default_rng(seed)
    sets = np.array([rng.choice(Xtr.shape[1], size, replace=False)
                     for _ in range(n_sets)])
    ranks = np.array([stats.rankdata(SVC(kernel="linear").fit(Xtr[:, s], y_train)
                                     .decision_function(Xte[:, s])) for s in sets])

    def counts(y):                      # AUC of all sets at once from the ranks
        n1, n0 = y.sum(), len(y) - y.sum()
        aucs = (ranks @ y - n1 * (n1 + 1) / 2) / (n1 * n0)
        best = sets[np.argsort(-aucs, kind="stable")[:top]]
        return np.bincount(best.ravel(), minlength=Xtr.shape[1])

    obs = counts(y_fu.astype(float))
    null_max = np.array([counts(rng.permutation(y_fu).astype(float)).max()
                         for _ in range(n_perm)])
    p_fwe = (1 + (null_max[:, None] >= obs).sum(0)) / (1 + n_perm)
    return obs / (top * size / Xtr.shape[1]), p_fwe