"""### Classification into Performance Groups (Cut-offs)"""

def apply_cutoffs(values, lo_cut, hi_cut, lower_is_better=False):
    """1 = high, 0 = low, -1 = middle (excluded). The cut-offs are fixed at
    baseline (Supplementary Table S4) and applied unchanged to follow-up."""
    v = np.asarray(values)
    if lower_is_better:                   # alpha: high performers lie below lo_cut
        return np.where(v < lo_cut, 1, np.where(v >= hi_cut, 0, -1))
    return np.where(v >= hi_cut, 1, np.where(v < lo_cut, 0, -1))

"""### Standardization (Z-Score)"""

def zscore(X_fit, *X_apply):
    """Standardize with mean and SD of X_fit only: all 69 baseline participants
    for the final model, the outer training set within nested CV."""
    mu, sd = X_fit.mean(0), X_fit.std(0, ddof=1)
    sd[sd == 0] = 1
    return [(X - mu) / sd for X in (X_fit, *X_apply)]

"""### Calculation of the AUC (Area Under the Curve)"""

def auc(y, s):
    """ROC-AUC via ranks (Mann-Whitney U), ties averaged."""
    y, r = np.asarray(y), stats.rankdata(s)
    n1, n0 = y.sum(), len(y) - y.sum()
    return (r[y == 1].sum() - n1 * (n1 + 1) / 2) / (n1 * n0)