"""### 2. Cross-Validation Scoring
This function calculates the k-fold cross-validated ROC-AUC or classification accuracy using a linear Support Vector Classifier (SVC).
"""

def cv_score(X, y, k, metric, scale=False):
    """Mean k-fold cross-validated ROC-AUC or accuracy of a linear SVM (C = 1);
    scale=True re-standardizes within each inner fold (used in rank_features)."""
    vals = []
    for tr, te in StratifiedKFold(k).split(X, y):
        Xtr, Xte = X[tr], X[te]
        if scale:
            mu, sd = Xtr.mean(0), Xtr.std(0)
            sd[sd == 0] = 1
            Xtr, Xte = (Xtr - mu) / sd, (Xte - mu) / sd
