"""## Intraclass Correlation Coefficient (ICC)
This function calculates the ICC(2,1) (two-way random effects, absolute agreement, single measure) to assess test-retest reliability.
"""

def icc21(x, y):
    """ICC(2,1): two-way random effects, absolute agreement, single measure
    (Shrout & Fleiss, 1979)."""
    d = np.c_[x, y]
    n, k = d.shape
    gm = d.mean()
    ssr = k * ((d.mean(1) - gm) ** 2).sum()
    ssc = n * ((d.mean(0) - gm) ** 2).sum()
    sse = ((d - gm) ** 2).sum() - ssr - ssc
    msr, msc, mse = ssr / (n - 1), ssc / (k - 1), sse / ((n - 1) * (k - 1))
    return (msr - mse) / (msr + (k - 1) * mse + k * (msc - mse) / n)

"""## Session Change Analysis
This function performs paired two-sided t-tests, calculates effect size ($d_z$), and applies Benjamini-Hochberg false discovery rate correction to evaluate changes between sessions.
"""

def session_change(X_base, X_fu):
    """Paired two-sided t tests per feature, effect size d_z and Benjamini-Hochberg
    false discovery rate across the 136 features."""
    t, p = stats.ttest_rel(X_fu, X_base)
    d = X_fu - X_base
    return t, d.mean(0) / d.std(0, ddof=1), p, multipletests(p, method="fdr_bh")[1]