"""### 3. Permutation Test and P-Value Calculation"""

def permutation_p(X, y, observed, X_fu=None, y_fu=None, n_perm=5000, seed=1,
                  **kw):
    """The entire nested procedure is repeated with shuffled baseline labels (one
    outer repetition each). For the nested transfer, fold models trained on
    shuffled labels are tested against the true follow-up labels.
    observed = (mean nested CV AUC, mean nested transfer AUC)."""
    rng = np.random.default_rng(seed)
    null = []
    for p in range(n_perm):
        b, f = nested_cv(X, rng.permutation(y), X_fu, y_fu, repeats=1,
                         seed=seed + p, **kw)
        null.append([b[0], f[0] if f is not None else np.nan])
    null = np.array(null)
    return [(1 + np.sum(null[:, j] >= o)) / (1 + n_perm)
            for j, o in enumerate(observed) if o is not None]